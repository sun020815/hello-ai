"""最小改动拆解：同一句话只换一个词，看精排分怎么动。

起因：「一周减几斤算正常」0.9047 被拒，而「减脂一周掉多少斤正常」0.9958 过线。
两句同义，差 0.09 —— 不是「量化问法不行」（全组均分 0.9787），是某个具体措辞
让 reranker 掉分。用逐词替换定位到底是哪个字。

对照组用 diet-food-04（脂肪与菜），问「坚果」时 0.86、问「炒菜油」时 0.996，
怀疑这条 chunk 把四样东西（蛋黄/坚果/油/菜）塞在一起，单独问某一样时语义被摊薄。
"""
import main

TH = main.RERANK_THRESHOLD

GROUPS = {
    "lose-01：「一周减几斤算正常」逐词替换": [
        "一周减几斤算正常",
        "一周减几斤正常",
        "一周减多少斤算正常",
        "一周减多少斤正常",
        "减脂一周掉多少斤正常",
        "减脂期一周掉多少斤正常",
        "减脂一周掉几斤算正常",
        "一周掉几斤算正常",
        "一周瘦几斤算正常",
        "减脂一周减几斤算正常",
    ],
    "diet-food-04：「坚果一天吃多少」换说法": [
        "坚果一天吃多少",
        "一天吃多少坚果",
        "坚果吃多少",
        "坚果一天吃一把够吗",
        "坚果一天吃几颗",
        "坚果怎么安排",
        "减脂期坚果吃多少",
        "坚果能吃吗",
        "炒菜油一天用多少",
        "蛋黄一天吃几个",
    ],
}

for title, qs in GROUPS.items():
    print("=" * 70)
    print(title)
    print("=" * 70)
    for q in qs:
        r = main.rank_one(q)
        t = r[0]
        flag = "过" if t["score"] >= TH else "拒"
        print(f"  {t['score']:.4f} [{flag}]  {q:<26} -> {t['id']:<13} {t['topic']}")
