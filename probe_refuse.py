def top_score(q):
    """和线上 search_kb_rerank 相同路径：向量召回 12 条 -> 精排 -> 取最高分。"""
    hits, ranking = app.search_kb_rerank(q)
    top = ranking[0]
    return top["score"], top["topic"], top["id"], bool(hits)


