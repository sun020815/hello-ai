def score_with(q, use_rewrite):
    """和 search_kb_rerank 同样的路径，精排文本可临时换。
    向量召回一律用原库 —— 改开头一句对向量影响很小（长文本取平均），
    这样两次调用召回池完全相同，比的只有精排判断。"""
    app.USE_DOC2QUERY = False
    qv = app.embed([q])[0]
    kbv = app.get_kb_vectors()
    recalled = sorted(
        ((app.cosine(qv, kv), d) for d, kv in zip(app.KB, kbv)),
        key=lambda x: x[0], reverse=True,
    )[: app.RECALL_K]
    cand = [dict(d) for _, d in recalled]
    if use_rewrite:
        for d in cand:
            if d["id"] in REWRITES:
                d["text"] = REWRITES[d["id"]][1]
    out = app.rerank(q, [app.rerank_text(d) for d in cand])
    rows = [(cand[s["index"]]["id"], cand[s["index"]]["topic"], s["score"]) for s in out]
    rows.sort(key=lambda r: -r[2])
    return rows


def main():
    print("对比：只改 chunk 开头那句话，其他全不动\n")
    for cid, variants in REWRITES.items():
        print(f"[{cid}]")
        print(f"  原：{variants[0][:44]}...")
        print(f"  改：{variants[1][:44]}...")
        for q in PROBES[cid]:
            base = score_with(q, False)
            new = score_with(q, True)
            b = next(((n, r) for n, r in enumerate(base, 1) if r[0] == cid), None)
            w = next(((n, r) for n, r in enumerate(new, 1) if r[0] == cid), None)
            bs = b[1][2] if b else 0.0
            ws = w[1][2] if w else 0.0
            br = b[0] if b else "-"
            wr = w[0] if w else "-"
            mark = ""
            if bs < 0.50 <= ws:
                mark = "  跨过门槛"
            elif ws - bs > 0.05:
                mark = "  明显上升"
            elif ws - bs < -0.05:
                mark = "  **下降**"
            print(f"  {q:<20} {bs:.4f}(第{br}) -> {ws:.4f}(第{wr})  "
                  f"{ws - bs:+.4f}{mark}")
        print()


if __name__ == "__main__":
    main()
