"""定位真因：短问法 vs 缺领域词。

上一轮实验有泄漏 —— 手工写的「常见问法」里直接包含了测试那句，等于自己给自己
出题，0.86→0.97 的结论不成立。README 里还躺着一次 doc2query 全量实验：
hit@1 92.6→88.4（-4.2），整体 83.0→87.5，但那是「拒答换命中」——多拦 13 条
错答（零收益，生成层本来兜得住）+ 多拒 4 条真答案（纯损失），所以当时关掉了。

这次先不动方案，只问一个问题：掉分的原因是「问法短」还是「缺领域词」？
两个假说预测不同的修法，必须分开。

  假说 S（短）：信息量不足，reranker 对极短查询天然没信心。修法 = 扩写。
  假说 D（缺领域词）：库里全是「减脂期…」开头，问法不带场景就锚不住。修法 = 补领域词。

同时必须验负例：补词会不会让「肌酸一天吃多少」这类库外问题也过线。
如果会，任何「一律补词」的方案都是拒答换命中，不能做。
"""
import main

TH = main.RERANK_THRESHOLD


def top1(q):
    r = main.rank_one(q)
    return r[0]


def show(title, qs):
    print("=" * 72)
    print(title)
    print("=" * 72)
    for q in qs:
        t = top1(q)
        flag = "过" if t["score"] >= TH else "拒"
        print(f"  {t['score']:.4f} [{flag}] {len(q):>2}字  {q:<28} -> {t['id']:<13} {t['topic']}")


# A. 同一件事，从短到长铺开。若单调升 -> 支持假说 S
A_NUT = [
    "坚果吃多少",
    "坚果一天吃多少",
    "减脂坚果一天吃多少",
    "减脂期坚果一天吃多少",
    "减脂期每天坚果吃多少克",
    "我在减脂期，坚果一天吃多少克合适",
]
A_WEEK = [
    "一周瘦几斤",
    "一周瘦几斤算正常",
    "减脂一周瘦几斤算正常",
    "减脂期一周瘦几斤算正常",
    "减脂期一周瘦几斤算正常范围",
    "我在减脂，一周瘦几斤算正常",
]

# B. 长度固定、只换有没有领域词。若带「减脂」明显高 -> 支持假说 D
B_FIXED = [
    ("七天掉几斤才算正常", 9),
    ("减脂七天掉几斤算正常", 11),
    ("坚果每天吃多少才算够", 10),
    ("减脂坚果每天吃多少够", 11),
]

# C. 负例：库外问题，看补词后会不会被放行（决定性对照）
C_NEG = [
    "肌酸一天吃多少",
    "减脂期肌酸一天吃多少",
    "减脂期要不要吃肌酸",
    "我膝盖疼吃什么",
    "减脂期膝盖疼吃什么",
    "蛋白粉一天喝几勺",
    "减脂期蛋白粉一天喝几勺",
]

if __name__ == "__main__":
    print(f"阈值 {TH}\n")
    show("A1 坚果：由短到长", A_NUT)
    show("A2 一周瘦几斤：由短到长", A_WEEK)
    show("B 长度接近，只差「减脂」两个字", [q for q, _ in B_FIXED])
    show("C 负例（库外）：补词后会不会误放行", C_NEG)
